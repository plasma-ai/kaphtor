#!/usr/bin/env python3
"""Freeze the generated components into SHA256SUMS and stamp PROTOCOL.md.

Run after build_templates.py, build_register.py, build_transducer.py and
render_la.py have produced their outputs and PROTOCOL.md has been written.
Appends (never removes) hashes for every file under data/, controls/, vendor/
and scripts/common/, records git HEAD and the freeze time in
PROTOCOL.md's "Freeze record" section, and appends a run_manifest entry.
Refuses to run if PROTOCOL.md already carries a freeze record (pass --refreeze
with a reason after Tom's sign-off).
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common.paths import CONTROLS, DATA, MANIFEST, PKG, PROTOCOL, SHA_FILE, VENDOR, read_sums, sha256  # noqa: E402

FREEZE_MARK = "## Freeze record"


def frozen_files() -> list[Path]:
    out: list[Path] = []
    for base in (DATA, CONTROLS, VENDOR, PKG / "scripts" / "common"):
        for p in sorted(base.rglob("*")):
            if p.is_file() and "__pycache__" not in p.parts and not p.name.endswith(".pyc"):
                out.append(p)
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--refreeze", metavar="REASON", default=None)
    args = ap.parse_args()
    text = PROTOCOL.read_text(encoding="utf-8") if PROTOCOL.exists() else ""
    if FREEZE_MARK in text and not args.refreeze:
        print("PROTOCOL.md already frozen; pass --refreeze <reason> after sign-off")
        return 2
    sums = read_sums()
    files = frozen_files()
    for p in files:
        sums[p.relative_to(PKG).as_posix()] = sha256(p)
    lines = ["# SHA-256 of every frozen file, relative to the package root. Generated by freeze_inputs.py / freeze_protocol.py."]
    lines += [f"{d}  {rel}" for rel, d in sorted(sums.items())]
    SHA_FILE.write_text("\n".join(lines) + "\n")
    head = subprocess.check_output(["git", "-C", str(PKG.parent), "rev-parse", "HEAD"], text=True).strip()
    now = datetime.now(timezone.utc).isoformat()
    record = (f"\n{FREEZE_MARK}\n\n- frozen_at: {now}\n- repo_head: {head}\n"
              f"- files_hashed: {len(sums)}\n- sha256sums_sha256: {sha256(SHA_FILE)}\n")
    if args.refreeze:
        record += f"- refreeze_reason: {args.refreeze}\n"
    PROTOCOL.write_text(text.rstrip() + "\n" + record)
    entries = json.loads(MANIFEST.read_text()) if MANIFEST.exists() else []
    entries.append({"ts": now, "script": "freeze_protocol.py", "args": vars(args),
                    "files_hashed": len(sums), "repo_head": head})
    MANIFEST.write_text(json.dumps(entries, indent=1))
    print(f"frozen {len(sums)} files at {now} (HEAD {head[:10]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
