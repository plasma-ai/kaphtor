#!/usr/bin/env python3
"""Render the CH → Linear A → Linear B → Semitic acrophony lineage table.

Joins the CH→LA chains (cretan_hieroglyphic_ch_la_correspondences.json), the CH
value tiers (cretan_hieroglyphic_sign_values.json) and the hand-curated Semitic
words, matches and verdicts in data/linear-a/sign_acrophony_lineage.json. Chains and tiers
come from the CH files; only the curated file carries Semitic content, so a rerun
never overwrites it.

Writes the table to --out (default: the user cache, `CACHE/linear-a/sign-acrophony-lineage.md`). An existing
output is copied into `--backups` (default `tools.paths.BACKUPS`) before it is rewritten.

  python tools/linear_a/render_sign_acrophony.py [--out FILE] [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
    __package__ = "tools.linear_a"

from ..paths import BACKUPS, CACHE, LINEAR_A_DATA, NotInCheckout, require

CH_DIR = LINEAR_A_DATA / "cretan-hieroglyphic"
CHAINS = CH_DIR / "cretan_hieroglyphic_ch_la_correspondences.json"
CH_VALUES = CH_DIR / "cretan_hieroglyphic_sign_values.json"
CURATED = LINEAR_A_DATA / "sign_acrophony_lineage.json"
SIGN_REGISTRY = LINEAR_A_DATA / "sign-registry.json"
OUT = CACHE / "linear-a" / "sign-acrophony-lineage.md"

MATCH_ORDER = ["CV", "C", "V", "V-guttural-mismatch", "none"]


def read(path: Path):
    return json.loads(require(path, path.name).read_text(encoding="utf-8"))


def cell(s) -> str:
    return (str(s) if s not in (None, "") else "—").replace("|", "\\|").replace("\n", " ")


def chain_text(rec: dict, names: dict[str, str]) -> str:
    la = rec["linear_a_sign"]
    value = rec.get("linear_a_name") or rec.get("linear_b_value") or "?"
    if value == "?":
        value = names.get(la) or "?"
    return f"{la} {value}"


def chain_source(rec: dict) -> str:
    src = rec.get("source", "")
    for key, short in (("Ferrara-Montecchi-Valerio", "FMV 2022"), ("Davis 2024", "Davis 2024"),
                       ("Meissner & Salgarella", "M&S 2024"), ("corpus-distributional", "corpus")):
        if key in src:
            return short
    return src[:20]


LANG = {"Proto-Semitic": "PS", "Hebrew": "Heb.", "Ugaritic": "Ug.", "Akkadian": "Akk.",
        "Aramaic": "Aram.", "Syriac": "Syr.", "Arabic": "Ar.", "Phoenician": "Phoen.",
        "Amorite": "Amor.", "Geez": "Gəʿ.", "Ge'ez": "Gəʿ.", "Sabaic": "Sab.", "Egyptian": "Eg."}


def cognate_text(cogs: dict) -> str:
    return "; ".join(f"{LANG.get(lang, lang)} {form}" for lang, form in (cogs or {}).items())


def build(chains: list[dict], tiers: dict, curated: dict,
          names: dict[str, str]) -> tuple[str, Counter, Counter]:
    by_ch: dict[str, list[dict]] = {}
    for rec in chains:
        by_ch.setdefault(rec["ch_number"], []).append(rec)
    entries = {e["ch"]: e for e in curated["signs"]}
    meta = curated["meta"]

    frozen, posthoc = Counter(), Counter()
    tested, untested = [], []
    for ch in sorted(by_ch):
        (tested if ch in entries else untested).append(ch)
        for c in entries.get(ch, {}).get("candidates", []):
            (frozen if c.get("frozen") else posthoc)[c.get("match", "none")] += 1

    lines = [
        "# Sign Acrophony Lineage: CH → Linear A → Linear B → Semitic",
        "",
        ("Generated by `tools/linear_a/render_sign_acrophony.py` from the CH→LA chain file, the CH value "
         "tiers and the curated `data/linear-a/sign_acrophony_lineage.json`. Edit the curated file, then "
         "rerun; do not edit this table by hand."),
        "",
        (f"**Status.** {meta['battery_result']} This table records lineage; it assigns no values. "
         "Frozen words are the battery's pre-committed choices; post-hoc words were chosen after "
         "the fact and carry no statistical weight."),
        "",
        f"**Labels.** {meta['label_caveat']}",
        "",
        ("**Match classes** (after the project's spelling rules): "
         "`CV` consonant series and vowel both give the LA value; `C` series only; `V` an initial "
         "guttural drops to the bare vowel sign with the right vowel; `V-guttural-mismatch` it "
         "drops with the wrong vowel; `none`."),
        "",
        "| Words | " + " | ".join(MATCH_ORDER) + " |",
        "|---|" + "---|" * len(MATCH_ORDER),
        "| frozen | " + " | ".join(str(frozen[m]) for m in MATCH_ORDER) + " |",
        "| post-hoc | " + " | ".join(str(posthoc[m]) for m in MATCH_ORDER) + " |",
        "",
        "## Lineage table",
        "",
        "| CH | Picture | LA value (chain) | CH tier | Semitic word | Cognates | Match | Verdict |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for ch in tested:
        e = entries[ch]
        recs = by_ch[ch]
        la = "<br>".join(f"{chain_text(r, names)} ({chain_source(r)})" for r in recs)
        picture = e["picture"] + ("" if e.get("label_status") != "plate-checked" else " (plates)")
        tier = (tiers.get(ch) or {}).get("tier", "")
        cands = e.get("candidates") or [{}]
        for i, c in enumerate(cands):
            word = f"{c.get('ps', '')} \"{c.get('gloss', '')}\"" if c else ""
            if c and not c.get("frozen"):
                word += " (post-hoc)"
            if c and c.get("verified") is False:
                word += " †"
            first = i == 0
            head = [cell(x) for x in (ch, picture, la, tier)] if first else ["", "", "", ""]
            lines.append("| " + " | ".join(head + [cell(x) for x in (
                word, cognate_text(c.get("cognates")), c.get("match", ""))]
                + [cell(e["verdict"]) if first else ""]) + " |")
    lines += ["", "† unverified.", ""]

    notes = [(ch, entries[ch]["notes"]) for ch in tested if entries[ch].get("notes")]
    if notes:
        lines += ["## Notes", ""]
        lines += [f"- **CH {ch}.** {n}" for ch, n in notes]
        lines.append("")

    lines += ["## Untestable chains", "",
              "No identified picture, so no word to test:", "",
              "| CH | LA value (chain) | CH tier |", "|---|---|---|"]
    for ch in untested:
        la = "; ".join(f"{chain_text(r, names)} ({chain_source(r)})" for r in by_ch[ch])
        lines.append(f"| {ch} | {cell(la)} | {cell((tiers.get(ch) or {}).get('tier'))} |")
    lines += ["", "## Sources", ""] + [f"- {s}" for s in meta["sources"]] + [""]
    return "\n".join(lines), frozen, posthoc


def main() -> int:
    """Exit 2 with the file's name when a data file is not in the checkout."""
    try:
        return _run()
    except NotInCheckout as e:
        print(f"stopped: {e}", file=sys.stderr)
        return 2


def _run() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--dry-run", action="store_true", help="report what would be written; write nothing")
    p.add_argument("--out", type=Path, default=OUT, help="where to write the table (default: the user cache)")
    p.add_argument("--backups", type=Path, default=BACKUPS, help="where an existing output is copied first")
    args = p.parse_args()
    out = args.out

    chains = read(CHAINS)["records"]
    tiers = read(CH_VALUES)["signs"]
    curated = read(CURATED)
    unknown = {e["ch"] for e in curated["signs"]} - {r["ch_number"] for r in chains}
    if unknown:
        print(f"curated signs with no chain record: {sorted(unknown)}", file=sys.stderr)
        return 1

    names = {s["ab_number"]: s.get("name", "") for s in read(SIGN_REGISTRY)["signs"]}
    text, frozen, posthoc = build(chains, tiers, curated, names)
    print(f"chains {len(chains)}, CH signs {len({r['ch_number'] for r in chains})}, curated {len(curated['signs'])}")
    print(f"frozen matches {dict(frozen)}; post-hoc {dict(posthoc)}")
    if args.dry_run:
        print("dry run: nothing written")
        return 0

    if out.exists():
        stamp = datetime.now().astimezone().strftime("%Y%m%d-%H%M%S")
        args.backups.mkdir(parents=True, exist_ok=True)
        dest = args.backups / f"{out.stem}-{stamp}{out.suffix}"
        shutil.copy2(out, dest)
        print(f"backup {dest}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
